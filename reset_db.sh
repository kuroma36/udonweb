#!/bin/bash
# ==============================================================================
# 香川うどん巡礼アプリ (UdonWeb) - 全データ初期化バッチ
# 使い方: ./reset_db.sh または bash reset_db.sh
# ==============================================================================

set -e

# スクリプトがあるプロジェクトディレクトリへ移動
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "========================================================"
echo " 🍜 香川うどん巡礼アプリ 全データ初期化バッチ"
echo "========================================================"

# Django 管理コマンドを実行（--no-input で自動実行、引数に -i を渡せば対話確認可能）
if [ "$1" == "-i" ]; then
    ./venv/bin/python manage.py reset_all_data
else
    ./venv/bin/python manage.py reset_all_data --no-input
fi

echo ""
echo "========================================================"
echo " ✅ 初期化が完了しました。"
echo " サーバーに反映する場合は以下を実行してください:"
echo "   sudo systemctl restart gunicorn"
echo "========================================================"
